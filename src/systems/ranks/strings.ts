const GEMATRIA = ['א', 'ב', 'ג', 'ד', 'ה', 'ו', 'ז', 'ח', 'ט', 'י'];
/** Tier numeral in the edition's style: Roman in English, Hebrew letters (א׳ ב׳ ג׳) in Hebrew. */
export function tierNumeral(n: number, locale: Locale, roman: string): string {
  if (locale !== 'he') return roman;
  return n >= 1 && n <= GEMATRIA.length ? `${GEMATRIA[n - 1]}׳` : String(n);
}

