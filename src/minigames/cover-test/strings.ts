const HE_PHORIA = { eso: 'אזופוריה', exo: 'אקסופוריה', hyperR: 'היפרפוריה R', hyperL: 'היפרפוריה L' } as const;
export function kindLabelHe(k: string, dir: string, eye?: string): string {
  if (k === 'ortho' || dir === 'none') return 'אורתופוריה';
  const d = dir as keyof typeof HE_TROPIA;
  if (k === 'phoria') return HE_PHORIA[d];
  const vertical = dir === 'hyperR' || dir === 'hyperL';
  const who = vertical ? (dir === 'hyperR' ? 'R' : 'L') : eye === 'alternating' ? 'מתחלפת' : eye ? (eye === 'OD' ? 'R' : 'L') : '';
  const kind = k === 'tropia' ? 'קבועה' : 'לסירוגין';
  return `${HE_TROPIA[d]} ${kind}${who ? ` ${who}` : ''}`;
}
